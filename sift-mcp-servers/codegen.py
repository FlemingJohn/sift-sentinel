if __name__ == "__main__":
    registry_path = sys.argv[1] if len(sys.argv) > 1 else "registry.json"
    out_dir       = sys.argv[2] if len(sys.argv) > 2 else "servers"
    wsl_distro    = sys.argv[3] if len(sys.argv) > 3 else "Ubuntu-22.04"
    generate(registry_path, out_dir, wsl_distro)
