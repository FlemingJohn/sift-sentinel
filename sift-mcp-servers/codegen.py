# ── helpers ──────────────────────────────────────────────────────────────────

def _run(binary: str, args: list, timeout: int = 300) -> dict:
    """
    Core subprocess runner used by every tool in this server.
    Returns a structured dict — never raw text.
    Logs every call to the audit trail.
    """
    resolved = shutil.which(binary)
    if not resolved:
        return {{
            "error":     f"{{binary}} not found on PATH",
            "installed": False,
            "binary":    binary,
        }}

    cmd   = [resolved] + [str(a) for a in args if a is not None and a != ""]
    start = datetime.now(timezone.utc)

    try:
        result = subprocess.run(
            cmd,
            capture_output=True,
            text=True,
            timeout=timeout,
        )
        duration_ms = int(
            (datetime.now(timezone.utc) - start).total_seconds() * 1000
        )
        entry = {{
            "tool":        binary,
            "server":      "sift-{server}",
            "command":     " ".join(cmd),
            "exit_code":   result.returncode,
            "stdout":      trunc.truncate(result.stdout),
            "stderr":      result.stderr.strip() or None,
            "timestamp":   start.isoformat(),
            "duration_ms": duration_ms,
            "installed":   True,
        }}

    except subprocess.TimeoutExpired:
        entry = {{
            "tool":      binary,
            "server":    "sift-{server}",
            "command":   " ".join(cmd),
            "error":     f"timeout after {{timeout}}s",
            "timestamp": start.isoformat(),
            "installed": True,
        }}

    except Exception as e:
        entry = {{
            "tool":      binary,
            "server":    "sift-{server}",
            "command":   " ".join(cmd),
            "error":     str(e),
            "timestamp": start.isoformat(),
            "installed": True,
        }}

    audit.log(entry)
    return entry


# ── tools ─────────────────────────────────────────────────────────────────────
{tool_functions}

# ── server entry point ────────────────────────────────────────────────────────

def main():
    """Console-script entry point used by pyproject.toml [project.scripts]."""
    mcp.run()


if __name__ == "__main__":
    main()
'''


TOOL_TEMPLATE = '''
