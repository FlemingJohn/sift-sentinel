def generate(
    registry_path: str = "registry.json",
    out_dir: str = "servers",
    wsl_distro: str = "Ubuntu-22.04",
):
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)

    with open(registry_path) as f:
        registry = json.load(f)

    servers    = registry["servers"]
    generated  = []

    print(f"\n[codegen] reading {registry_path}")
    print(f"[codegen] writing to ./{out_dir}/\n")

    # ── write shared.py ───────────────────────────────────────────────────────
    shared_path = out / "shared.py"
    shared_path.write_text(SHARED_TEMPLATE)
    print(f"  wrote  shared.py")

    # ── write one server file per category ────────────────────────────────────
    for server, tools in sorted(servers.items()):
        tool_functions = ""
        seen           = set()

        for tool in tools:
            binary = tool["binary"]
            if binary in seen:
                continue   # dedup within server
            seen.add(binary)

            tool_functions += TOOL_TEMPLATE.format(
                fn_name = tool["fn_name"],
                binary  = binary,
                package = tool["package"],
            )

        server_code = SERVER_TEMPLATE.format(
            server         = server,
            tool_count     = len(seen),
            tool_functions = tool_functions,
        )

        out_file = out / f"sift_{server}.py"
        out_file.write_text(server_code)
        print(f"  wrote  sift_{server}.py   ({len(seen)} tools)")
        generated.append((server, str(out_file.resolve())))

    # ── write claude_desktop_config.json ──────────────────────────────────────
    entries = []
    for server, abs_path in generated:
        entries.append(SERVER_ENTRY_TEMPLATE.format(
            server      = server,
            server_path = to_wsl_path(abs_path),
            wsl_distro  = wsl_distro,
        ))

    config = CONFIG_TEMPLATE.format(
        server_entries = ",\n".join(entries)
    )

    config_path = out / "claude_desktop_config.json"
    config_path.write_text(config)
    print(f"\n  wrote  claude_desktop_config.json")

    # ── write pyproject.toml so `uvx --from <path> sift-<server>` works ───────
    # Includes both codegen-generated servers AND hand-written sift_*.py files
    # that already exist in `out/` (e.g. sift_attack.py, sift_defend.py).
    auto_names = {server for server, _ in generated}
    hand_names: list[str] = []
    for sf in sorted(out.glob("sift_*.py")):
        stem = sf.stem
        name = stem.removeprefix("sift_")
        if name in auto_names:
            continue
        # heuristic: skip helper modules that don't expose main()
        text = sf.read_text(encoding="utf-8", errors="ignore")
        if "def main()" not in text or "FastMCP(" not in text:
            continue
        hand_names.append(name)
        print(f"  detected hand-written server: sift-{name} ({sf.name})")

    all_servers = [s for s, _ in generated] + hand_names

    script_entries = "\n".join(
        f'"sift-{s}" = "sift_{s}:main"' for s in all_servers
    )
    # py-modules must include every module the entry points reference,
    # plus any helper modules they import (e.g. sift_attack_map).
    extra_helpers = []
    for sf in sorted(out.glob("*.py")):
        stem = sf.stem
        if stem == "shared" or stem.startswith("sift_"):
            # sift_attack_map etc. — included if not already an entry point
            if stem not in {f"sift_{s}" for s in all_servers}:
                extra_helpers.append(stem)
    module_list = ", ".join(
        f'"{m}"' for m in sorted({"shared", *extra_helpers, *(f"sift_{s}" for s in all_servers)})
    )
    pyproject = PYPROJECT_TEMPLATE.format(
        script_entries = script_entries,
        module_list    = module_list,
    )
    (out / "pyproject.toml").write_text(pyproject)
    print(f"  wrote  pyproject.toml      ({len(all_servers)} entry points: "
          f"{len(generated)} generated + {len(hand_names)} hand-written)")

    # ── also extend claude_desktop_config.json with hand-written servers ──────
    for name in hand_names:
        abs_path = (out / f"sift_{name}.py").resolve()
        entries.append(SERVER_ENTRY_TEMPLATE.format(
            server      = name,
            server_path = to_wsl_path(str(abs_path)),
            wsl_distro  = wsl_distro,
        ))
    config_path.write_text(CONFIG_TEMPLATE.format(server_entries=",\n".join(entries)))
    if hand_names:
        print(f"  re-wrote claude_desktop_config.json with {len(hand_names)} hand-written entries")

    # ── summary ───────────────────────────────────────────────────────────────
    total = sum(len(t) for t in servers.values())
    print("\n" + "═" * 56)
    print("  CODEGEN COMPLETE")
    print("═" * 56)
    print(f"  Server files generated  : {len(generated)}")
    print(f"  Total tools             : {total}")
    print(f"  Output directory        : ./{out_dir}/")
    print()
    print("  Next steps:")
    print("  1. pip install mcp")
    print("  2. Copy claude_desktop_config.json to:")
    print("     %APPDATA%\\Claude\\claude_desktop_config.json")
    print("  3. Restart Claude Desktop")
    print("═" * 56)


